import { chromium } from '@playwright/test';

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 412, height: 915 }, colorScheme: 'light' });
await page.clock.install({ time: new Date('2026-09-06T08:00:00Z') });
await page.goto('http://127.0.0.1:42777/');
await page.getByRole('button', { name: '开始建造' }).click();
await page.getByRole('button', { name: '设置' }).click();
await page.getByRole('checkbox', { name: '开启极简模式' }).click();
await page.getByRole('button', { name: '计时', exact: true }).click();
await page.waitForTimeout(200);
await page.reload();
await page.waitForTimeout(400);
const read = (tag) => page.evaluate((tag) => ({ tag, now: new Date().toISOString(), idle: Boolean(document.querySelector('.minimal-idle')), veiled: Boolean(document.querySelector('.minimal-exit.is-veiled')), task: document.querySelector('.focus-task-context')?.textContent?.slice(0, 30) ?? null }), tag);
console.log(JSON.stringify(await read('after reload')));
await page.getByRole('button', { name: '开始专注', exact: true }).click();
await page.waitForTimeout(200);
await page.getByRole('button', { name: '关闭专注到' }).click();
await page.waitForTimeout(200);
console.log(JSON.stringify(await read('after first close')));
await page.getByRole('button', { name: '开始专注', exact: true }).click();
await page.waitForTimeout(200);
console.log(JSON.stringify(await read('sheet reopened')));
await page.locator('.minimal-end-sheet .primary').click();
await page.waitForTimeout(500);
console.log(JSON.stringify(await read('after submit')));
await page.waitForTimeout(2500);
console.log(JSON.stringify(await read('after +2.5s')));
await page.waitForTimeout(4000);
console.log(JSON.stringify(await read('after +6.5s')));
await browser.close();
